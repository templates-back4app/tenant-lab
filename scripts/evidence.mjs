// File: scripts/evidence.mjs · Node 22 ESM
// Turns the rows the test suites append to docs/evidence/.rows-local.jsonl into the evidence files:
//   docs/evidence/isolation-matrix-local-<date>.md   (one row per test: persona, attempt, HTTP/Parse code,
//                                                     body assertion, state assertion)
//   docs/evidence/files-h1-local-<date>.md           (the H1 rows, with the Back4app column "to measure")
// Wired into npm: `pretest` runs `--reset` (start a fresh collection), `posttest` writes the files, so the
// committed evidence always reflects ONE complete `npm test` run. Run dates use the local machine's date.
import { readFileSync, writeFileSync, rmSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { ROOT, args } from './lib/env.mjs';

const EVIDENCE_DIR = path.join(ROOT, 'docs', 'evidence');
const ROWS_FILE = path.join(EVIDENCE_DIR, '.rows-local.jsonl');
const a = args();

if (a.reset) {
  rmSync(ROWS_FILE, { force: true });
  process.exit(0);
}

if (!existsSync(ROWS_FILE)) {
  console.error('evidence: no .rows-local.jsonl — run `npm test` first.');
  process.exit(1);
}

const rows = readFileSync(ROWS_FILE, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
// One row per id: the LAST record of a run wins (re-runs within one `npm test` overwrite).
const byId = new Map();
for (const r of rows) byId.set(r.id, r);
const date = new Date().toISOString().slice(0, 10);

const order = (id) => {
  const m = id.match(/^([A-Z]+)(\d+)(.*)$/);
  const series = { T: 0, P: 1, R: 2, L: 3, C: 4, H: 5 }[m ? m[1] : 'Z'] ?? 9;
  return [series, m ? Number(m[2]) : 999, m ? m[3] : ''];
};
const sorted = [...byId.values()].sort((x, y) => {
  const [a1, a2, a3] = order(x.id); const [b1, b2, b3] = order(y.id);
  return a1 - b1 || a2 - b2 || (a3 < b3 ? -1 : a3 > b3 ? 1 : 0);
});

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (list) => [
  '| # | Persona | Attempt | HTTP / code | Body assertion | State assertion |',
  '|---|---|---|---|---|---|',
  ...list.map((r) => `| ${r.id} | ${esc(r.persona)} | ${esc(r.attempt)} | ${esc(r.status)} · ${esc(r.code)} | ${esc(r.body)} | ${esc(r.state)} |`),
].join('\n');

const matrix = sorted.filter((r) => r.evidence !== 'h1');
const h1 = sorted.filter((r) => r.evidence === 'h1');

const header = (title) => `# ${title} — LOCAL run, ${date}

Generated by \`npm test\` (scripts/evidence.mjs) from a single complete run against an in-process
parse-server 7.5.4 (PostgreSQL adapter, port 5433, database \`tenant_test\`). **Local evidence only** — the
Back4app run of the same suites is the live phase and produces its own file; local and live results are
compared in \`local-vs-live.md\` (live phase). Every assertion checks the response body AND the database state
(master-key read-back), not just the status code.
`;

writeFileSync(path.join(EVIDENCE_DIR, `isolation-matrix-local-${date}.md`), `${header('Isolation test matrix')}
${table(matrix)}

## Live-only rows (not measured locally, by design)

| What | Why live-only |
|---|---|
| T1–T15 on Back4app | the published numbers must come from the platform the article is about; this file is the development-speed run |
| H2 revocation DELAY distribution (10 runs, min/median/max after \`removeMember\`) | local loopback timing is meaningless for the claim; the local T9lq row above records the mechanism (LiveQuery auth cache) |
| H3 scale: tenant-scoped query p50/p95 at 1 vs 1,000 tenants | needs the real backend, plan and region; varied one factor at a time |
| H4 scale: the same query for a user in 1 / 10 / 50 tenants | same |
| Storage per tenant (Plan Usage before/after seeding) | Back4app dashboard measurement |

Suites in this run: ${[...new Set(matrix.map((r) => r.suite))].join(', ')} · ${matrix.length} matrix rows recorded at ${new Date().toISOString()}.
`);

writeFileSync(path.join(EVIDENCE_DIR, `files-h1-local-${date}.md`), `${header('H1 — are file attachments protected by the row\'s permissions?')}
${table(h1)}

## Local conclusion (parse-server 7.5.4 + @parse/fs-files-adapter)

- The raw Parse File URL serves the full file contents to anyone holding the URL — no App ID, key or session
  (T7). **H1 SUPPORTED locally.**
- The membership-checked Cloud function \`getAttachment\` delivers bytes to members only (H1c) — but it is an
  access path, not protection: the raw URL re-measured with the mitigation in place still answers 200.
- Therefore, on this storage, attachments are **excluded from the local isolation claim**. File names carry a
  random prefix (guessing returned 404), so the exposure is "anyone who ever got the URL keeps the file", not
  "anyone can enumerate files".

## Back4app: **to measure (live)**

| Measurement | Status |
|---|---|
| Raw file URL without a session on Back4app's file store | to measure (live) |
| \`getAttachment\` behaviour on Back4app (incl. whether Cloud Code's \`fetch\` of file URLs works on Node 19) | to measure (live) |
| Raw URL after deleting the row / tenant (T15 cleanup verified locally: HTTP 404 after \`deleteTenant\`) | to measure (live) |
| Any platform option for signed/expiring file URLs | to research + measure (live) |
`);

console.log(`evidence: wrote isolation-matrix-local-${date}.md (${matrix.length} rows) and files-h1-local-${date}.md (${h1.length} rows)`);
// Stale evidence from earlier dates is left in place deliberately (dated files are the house style);
// list what exists so a stale file is noticed:
for (const f of readdirSync(EVIDENCE_DIR).filter((f) => f.endsWith('.md')).sort()) console.log(`  docs/evidence/${f}`);
